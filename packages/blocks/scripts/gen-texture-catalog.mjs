// Generates src/texture-names.ts from the committed transparent-texture PNG set in
// apps/api/assets/textures/. Run via `pnpm --filter @sitewright/blocks gen:textures`; the
// `:check` variant fails CI if the generated list drifts from the committed PNG files.
import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const texturesDir = fileURLToPath(new URL('../../../apps/api/assets/textures', import.meta.url));
const names = readdirSync(texturesDir)
  .filter((f) => f.toLowerCase().endsWith('.png'))
  .map((f) => f.slice(0, -4))
  .sort();

const out = fileURLToPath(new URL('../src/texture-names.ts', import.meta.url));
const body = `// GENERATED by scripts/gen-texture-catalog.mjs — do not edit by hand.
// The transparent, tileable texture set (from transparenttextures.com). Each name maps to a PNG
// served at /authoring/textures/<name>.png (see apps/api/assets/textures/). Metadata only — the
// bytes live in apps/api/assets/textures/ and are served + materialised into exports by the API.
export const TEXTURE_NAMES: readonly string[] = [
${names.map((n) => `  ${JSON.stringify(n)},`).join('\n')}
];
`;
writeFileSync(out, body);
console.log(`Wrote ${names.length} texture names to src/texture-names.ts`);
