const COUNTRY_SET: ReadonlySet<string> = new Set(COUNTRY_CODES);

/** Whether `code` is a country a shop can ship to (uppercase ISO 3166-1 alpha-2, or `XK`). */
export function isCountryCode(code: string): boolean {
  return COUNTRY_SET.has(code);
}

/** A ship-to country: uppercase ISO 3166-1 alpha-2 (`DE`, `CH`), or `XK`. */
export const CountryCodeSchema = z
  .string()
  .length(2)
  .refine(isCountryCode, 'must be an uppercase ISO 3166-1 alpha-2 country code, e.g. DE');
