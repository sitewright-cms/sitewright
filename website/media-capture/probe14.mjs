import { launch, signedIn, OUT } from './lib.mjs';
import { writeFileSync } from 'node:fs';
const browser = await launch();
const ctx = await signedIn(browser, 'lena@northwind.example', 'Pw-secret-1', { scale: 1, width: 1600, height: 1000, reducedMotion: 'reduce' });
const page = await ctx.newPage();
await page.goto('/');
await page.getByRole('button', { name: /Example Project/ }).first().click();
await page.waitForTimeout(1200); await page.getByRole('button', { name: 'Case study: Alpine Outfitters /case-study/' }).click(); await page.getByRole('dialog', { name: /Case study/ }).waitFor();
await page.getByRole('button', { name: 'Content Editor', exact: true }).click();
const pv = page.frameLocator('iframe[title="Preview"]');
await pv.locator('[data-sw-text="cs_title"]').waitFor();
await page.waitForTimeout(2000);
const img = pv.locator('[data-sw-src], img[data-sw-image], main img').first();
console.log('img attrs', await img.evaluate((e) => [...e.attributes].map((a) => a.name + '=' + a.value.slice(0, 50)).join(' ')));
await img.click();
await page.waitForTimeout(1500);
await page.screenshot({ path: `${OUT}/x-img-click.png` });
writeFileSync(`${OUT}/x-img-click.aria.txt`, await page.locator('body').ariaSnapshot());
await browser.close();
