import { launch, signedIn, api, ok, OUT } from './lib.mjs';
const a = await api('lena@northwind.example', 'Pw-secret-1');
const { projects } = await ok(a.get('/projects'), 'projects');
const pid = projects.find((p) => p.slug === 'example').id;
console.log('delete fr', (await a.delete(`/projects/${pid}/locales/fr`)).status());
const browser = await launch();
const ctx = await signedIn(browser, 'lena@northwind.example', 'Pw-secret-1', { scale: 1, width: 1680, height: 720, reducedMotion: 'reduce' });
const page = await ctx.newPage();
page.on('response', (r) => { if (r.url().includes('/locales')) console.log('  net', r.request().method(), r.url().split('/projects/')[1], r.status()); });
await page.goto('/');
await page.getByRole('button', { name: /Example Project/ }).first().click();
await page.getByRole('tab', { name: 'Website Settings' }).click();
await page.getByRole('button', { name: 'Open Languages' }).click();
const dialog = page.getByRole('dialog', { name: 'Languages' });
await dialog.getByRole('button', { name: /Add language/ }).click();
const add = page.getByRole('dialog', { name: 'Add a language' });
await add.getByRole('searchbox').fill('Fren');
await add.getByRole('button', { name: 'French fr' }).click();
await page.waitForTimeout(2500);
await page.screenshot({ path: `${OUT}/x-lang1.png` });
console.log((await page.locator('body').ariaSnapshot()).split('\n').filter((l) => /dialog|button "(Save|Add|Confirm|French)|fr\b/.test(l)).slice(0, 15).join('\n'));
await browser.close();
